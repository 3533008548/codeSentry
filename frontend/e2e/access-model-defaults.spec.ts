import { test, expect } from '@playwright/test';
import { mkdtemp, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = fileURLToPath(new URL('../../', import.meta.url));
test('ordinary web files default to model candidates while explicit local, ignored and secret files stay protected', async ({ page, request }) => {
  const root = await mkdtemp(path.join(repo, '.venv', 'model-default-browser-fixture-'));
  for (const name of ['main.py', 'local.py', 'private.py', 'ignored.py']) await writeFile(path.join(root, name), 'VALUE = 1\n');
  await writeFile(path.join(root, '.gitignore'), 'ignored.py\n');
  await writeFile(path.join(root, '.env'), 'SYNTHETIC_SECRET_EXCLUDED=true\n');
  const auth = { 'X-CodeSentry-Token': (await (await request.get('/api/session')).json()).token };
  const before = await (await request.get('/api/e2e/semantic-transport', { headers: auth })).json();
  await page.goto('/');
  await page.locator('.add-workspace-inline').click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('项目目录', { exact: true }).fill(root);
  await dialog.getByLabel('工作空间名称').fill('默认模型范围验收');
  await expect(dialog.getByRole('checkbox', { name: '普通文件默认允许模型取材' })).toBeChecked();
  await expect(dialog.getByTestId('model-scope-input')).toHaveValue('**');
  await dialog.getByTestId('local-only-input').fill('local.py');
  await dialog.getByTestId('exclude-input').fill('private.py');
  await dialog.getByTestId('access-preview-button').click();
  const rows = dialog.getByTestId('access-preview').locator('li');
  await expect(rows.filter({ has: page.locator('code', { hasText: /^main.py$/ }) })).toContainText('模型候选');
  await expect(rows.filter({ has: page.locator('code', { hasText: /^local.py$/ }) })).toContainText('仅限本地分析');
  for (const name of ['private.py', 'ignored.py', '.env']) await expect(rows.filter({ has: page.locator('code', { hasText: name }) })).toContainText('完全排除');
  await dialog.getByLabel('我已核对以上文件访问范围', { exact: true }).check();
  await dialog.getByRole('button', { name: '打开工作空间', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  const id = page.url().split('/').at(-1)!;
  const base = `/api/workspaces/${id}`;
  const files = await (await request.get(base + '/files', { headers: auth })).json();
  expect(files.files.find((file: { path: string }) => file.path === 'main.py').access_mode).toBe('model_eligible');
  expect(files.files.find((file: { path: string }) => file.path === 'local.py').access_mode).toBe('local_only');
  expect(files.files.some((file: { path: string }) => ['.env', 'private.py', 'ignored.py'].includes(file.path))).toBe(false);
  const settings = await (await request.get(base + '/chat-settings', { headers: auth })).json();
  expect(settings.consent).toBe(false);
  await page.getByRole('button', { name: '工作空间设置', exact: true }).click();
  await dialog.getByRole('checkbox', { name: '普通文件默认允许模型取材' }).uncheck();
  await expect(dialog.getByTestId('model-scope-input')).toHaveValue('');
  await dialog.getByTestId('access-preview-button').click();
  await dialog.getByLabel('我已核对以上文件访问范围', { exact: true }).check();
  await dialog.getByRole('button', { name: '保存设置', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  const changed = await (await request.get(base, { headers: auth })).json();
  expect(changed.access_policy.settings).toEqual({ respect_gitignore: true, exclude: ['private.py'], local_only: ['local.py'], model_scope: [] });
  const after = await (await request.get('/api/e2e/semantic-transport', { headers: auth })).json();
  expect(after.requests).toBe(before.requests);
});
